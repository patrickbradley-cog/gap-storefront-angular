-- ============================================================================
-- GAPCAT catalog schema — PostgreSQL 16
-- Port of server/oracle/schema.sql. Identifiers are unquoted, so Postgres
-- stores them lowercase. Loaded by server/scripts/seed-postgres.ts.
-- ============================================================================

CREATE TABLE PRODUCTS (
  PRODUCT_ID    VARCHAR(16)    NOT NULL,
  NAME          VARCHAR(120)   NOT NULL,
  DEPARTMENT    VARCHAR(16)    NOT NULL,
  CATEGORY      VARCHAR(40)    NOT NULL,
  PRICE         NUMERIC(10,2)  NOT NULL,
  REGULAR_PRICE NUMERIC(10,2),
  PROMO         VARCHAR(200),
  BADGE         VARCHAR(60),
  REVIEW_SCORE  NUMERIC(3,2),
  REVIEW_COUNT  NUMERIC(5),
  DESCRIPTION   TEXT,
  LOADED_AT     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_PRODUCTS PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE PRODUCT_COLORS (
  COLOR_ID        INTEGER      GENERATED BY DEFAULT AS IDENTITY,
  PRODUCT_ID      VARCHAR(16)  NOT NULL,
  CC_ID           VARCHAR(16)  NOT NULL,
  NAME            VARCHAR(60)  NOT NULL,
  REGULAR_PRICE   VARCHAR(20),
  EFFECTIVE_PRICE VARCHAR(20),
  FLAG            VARCHAR(120),
  BADGE           VARCHAR(60),
  SWATCH          VARCHAR(400),
  ORD             NUMERIC(2)   DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUCT_COLORS PRIMARY KEY (COLOR_ID),
  CONSTRAINT FK_COLORS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID),
  CONSTRAINT UQ_COLOR_CC UNIQUE (PRODUCT_ID, CC_ID)
);

CREATE TABLE PRODUCT_IMAGES (
  IMAGE_ID INTEGER       GENERATED BY DEFAULT AS IDENTITY,
  COLOR_ID INTEGER       NOT NULL,
  URL      VARCHAR(400)  NOT NULL,
  ORD      NUMERIC(2)    DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUCT_IMAGES PRIMARY KEY (IMAGE_ID),
  CONSTRAINT FK_IMAGES_COLOR FOREIGN KEY (COLOR_ID) REFERENCES PRODUCT_COLORS (COLOR_ID)
);

CREATE TABLE PRODUCT_SIZES (
  PRODUCT_ID VARCHAR(16)  NOT NULL,
  SIZE       VARCHAR(8)   NOT NULL,
  ORD        NUMERIC(2)   DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUCT_SIZES PRIMARY KEY (PRODUCT_ID, SIZE),
  CONSTRAINT FK_SIZES_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
);

CREATE TABLE PRODUCT_FITS (
  PRODUCT_ID VARCHAR(16)  NOT NULL,
  FIT        VARCHAR(20)  NOT NULL,
  ORD        NUMERIC(2)   DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUCT_FITS PRIMARY KEY (PRODUCT_ID, FIT),
  CONSTRAINT FK_FITS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
);

CREATE INDEX IX_COLORS_PRODUCT ON PRODUCT_COLORS (PRODUCT_ID);
CREATE INDEX IX_IMAGES_COLOR ON PRODUCT_IMAGES (COLOR_ID);
CREATE INDEX IX_PRODUCTS_DEPT ON PRODUCTS (DEPARTMENT, CATEGORY);

COMMENT ON TABLE PRODUCTS IS 'Style-level catalog rows, one per style (pid)';
COMMENT ON COLUMN PRODUCTS.PRODUCT_ID IS 'Style id (pid) — colourway ids live on PRODUCT_COLORS.CC_ID';
COMMENT ON COLUMN PRODUCT_COLORS.CC_ID IS 'Colourway id (ccid)';
